function Auctionator.ProfessionQualityTemplates.GetLevels(itemID)
  return ITEM_TEMPLATES[itemID]
end

function Auctionator.ProfessionQualityTemplates.GetTier(itemID, itemLevel)
  local levels = ITEM_TEMPLATES[itemID]
  if not levels or not itemLevel then
    return nil
  end

  for tier, level in ipairs(levels) do
    if level == itemLevel then
      return tier
    end
  end

  return nil
end
